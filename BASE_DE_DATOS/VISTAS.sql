CREATE OR REPLACE VIEW V_FACTURA_RESUMEN AS
SELECT F.ID_FACTURA,
       F.SERIE,
       F.NUMERO,
       F.FECHA,
       D.ID_DEPARTAMENTO,
       D.NOMBRE AS DEPARTAMENTO,
       S.ID_SUCURSAL,
       S.CODIGO AS CODIGO_SUCURSAL,
       S.NOMBRE AS SUCURSAL,
       E.ID_EMPLEADO,
       E.NOMBRES || ' ' || E.APELLIDOS AS EMPLEADO,
       C.ID_CLIENTE,
       C.NIT,
       C.NOMBRES || ' ' || C.APELLIDOS AS CLIENTE,
       F.SUBTOTAL,
       F.IVA,
       F.TOTAL,
       ES.CODIGO AS ESTADO
FROM FACTURA F
JOIN SUCURSAL S ON S.ID_SUCURSAL = F.ID_SUCURSAL
JOIN MUNICIPIO M ON M.ID_MUNICIPIO = S.ID_MUNICIPIO
JOIN DEPARTAMENTO D ON D.ID_DEPARTAMENTO = M.ID_DEPARTAMENTO
JOIN EMPLEADO E ON E.ID_EMPLEADO = F.ID_EMPLEADO
JOIN CLIENTE C ON C.ID_CLIENTE = F.ID_CLIENTE
JOIN ESTADO ES ON ES.ID_ESTADO = F.ID_ESTADO;

CREATE OR REPLACE VIEW V_VENTA_DETALLE AS
SELECT F.ID_FACTURA,
       F.SERIE,
       F.NUMERO,
       F.FECHA,
       S.ID_SUCURSAL,
       S.NOMBRE AS SUCURSAL,
       F.ID_EMPLEADO,
       P.ID_PRODUCTO,
       P.CODIGO AS CODIGO_PRODUCTO,
       P.NOMBRE AS PRODUCTO,
       CA.ID_CATEGORIA,
       CA.NOMBRE AS CATEGORIA,
       MA.ID_MARCA,
       MA.NOMBRE AS MARCA,
       DF.CANTIDAD,
       DF.PRECIO_UNITARIO,
       DF.DESCUENTO,
       DF.SUBTOTAL AS TOTAL_LINEA,
       DF.FECHA_FIN_GARANTIA
FROM DETALLE_FACTURA DF
JOIN FACTURA F ON F.ID_FACTURA = DF.ID_FACTURA
JOIN SUCURSAL S ON S.ID_SUCURSAL = F.ID_SUCURSAL
JOIN PRODUCTO P ON P.ID_PRODUCTO = DF.ID_PRODUCTO
JOIN CATEGORIA CA ON CA.ID_CATEGORIA = P.ID_CATEGORIA
JOIN MARCA MA ON MA.ID_MARCA = P.ID_MARCA;

CREATE OR REPLACE VIEW V_VENTA_FORMA_PAGO AS
SELECT PA.ID_PAGO,
       PA.FECHA,
       F.ID_FACTURA,
       F.SERIE,
       F.NUMERO,
       S.ID_SUCURSAL,
       S.NOMBRE AS SUCURSAL,
       FP.ID_FORMA_PAGO,
       FP.NOMBRE AS FORMA_PAGO,
       B.NOMBRE AS BANCO,
       PA.NO_REFERENCIA,
       PA.NO_AUTORIZACION,
       PA.MONTO
FROM PAGO PA
JOIN FACTURA F ON F.ID_FACTURA = PA.ID_FACTURA
JOIN SUCURSAL S ON S.ID_SUCURSAL = F.ID_SUCURSAL
JOIN FORMA_PAGO FP ON FP.ID_FORMA_PAGO = PA.ID_FORMA_PAGO
LEFT JOIN BANCO B ON B.ID_BANCO = PA.ID_BANCO;

CREATE OR REPLACE VIEW V_GARANTIA_DETALLE AS
SELECT G.ID_GARANTIA,
       G.FECHA_RECLAMO,
       G.FECHA_RESOLUCION,
       F.SERIE,
       F.NUMERO,
       S.ID_SUCURSAL,
       S.NOMBRE AS SUCURSAL,
       P.ID_PRODUCTO,
       P.NOMBRE AS PRODUCTO,
       PR.NOMBRE AS PRODUCTO_REEMPLAZO,
       C.NOMBRES || ' ' || C.APELLIDOS AS CLIENTE,
       E.NOMBRES || ' ' || E.APELLIDOS AS EMPLEADO,
       G.DESCRIPCION_FALLA,
       G.TIPO_RESOLUCION,
       ES.CODIGO AS ESTADO,
       ES.NOMBRE AS NOMBRE_ESTADO,
       DF.FECHA_FIN_GARANTIA
FROM GARANTIA G
JOIN DETALLE_FACTURA DF ON DF.ID_DETALLE_FACTURA = G.ID_DETALLE_FACTURA
JOIN FACTURA F ON F.ID_FACTURA = DF.ID_FACTURA
JOIN SUCURSAL S ON S.ID_SUCURSAL = F.ID_SUCURSAL
JOIN CLIENTE C ON C.ID_CLIENTE = F.ID_CLIENTE
JOIN PRODUCTO P ON P.ID_PRODUCTO = DF.ID_PRODUCTO
LEFT JOIN PRODUCTO PR ON PR.ID_PRODUCTO = G.ID_PRODUCTO_REEMPLAZO
JOIN EMPLEADO E ON E.ID_EMPLEADO = G.ID_EMPLEADO
JOIN ESTADO ES ON ES.ID_ESTADO = G.ID_ESTADO;

CREATE OR REPLACE VIEW V_NOTA_CREDITO_DETALLE AS
SELECT NC.ID_NOTA_CREDITO,
       NC.SERIE,
       NC.NUMERO,
       NC.FECHA,
       F.SERIE AS SERIE_FACTURA,
       F.NUMERO AS NUMERO_FACTURA,
       S.ID_SUCURSAL,
       S.NOMBRE AS SUCURSAL,
       E.NOMBRES || ' ' || E.APELLIDOS AS EMPLEADO,
       NC.MOTIVO,
       P.NOMBRE AS PRODUCTO,
       DNC.CANTIDAD,
       DNC.MONTO,
       DNC.REINGRESA_INVENTARIO,
       ES.CODIGO AS ESTADO
FROM NOTA_CREDITO NC
JOIN FACTURA F ON F.ID_FACTURA = NC.ID_FACTURA
JOIN SUCURSAL S ON S.ID_SUCURSAL = F.ID_SUCURSAL
JOIN EMPLEADO E ON E.ID_EMPLEADO = NC.ID_EMPLEADO
JOIN ESTADO ES ON ES.ID_ESTADO = NC.ID_ESTADO
JOIN DETALLE_NOTA_CREDITO DNC ON DNC.ID_NOTA_CREDITO = NC.ID_NOTA_CREDITO
JOIN DETALLE_FACTURA DF ON DF.ID_DETALLE_FACTURA = DNC.ID_DETALLE_FACTURA
JOIN PRODUCTO P ON P.ID_PRODUCTO = DF.ID_PRODUCTO;

CREATE OR REPLACE VIEW V_EXISTENCIAS AS
SELECT S.ID_SUCURSAL,
       S.CODIGO AS CODIGO_SUCURSAL,
       S.NOMBRE AS SUCURSAL,
       CA.ID_CATEGORIA,
       CA.NOMBRE AS CATEGORIA,
       P.ID_PRODUCTO,
       P.CODIGO AS CODIGO_PRODUCTO,
       P.NOMBRE AS PRODUCTO,
       I.EXISTENCIA,
       I.STOCK_MINIMO,
       CASE WHEN I.EXISTENCIA <= I.STOCK_MINIMO THEN 'S' ELSE 'N' END AS BAJO_MINIMO,
       I.FECHA_ACTUALIZACION
FROM INVENTARIO I
JOIN SUCURSAL S ON S.ID_SUCURSAL = I.ID_SUCURSAL
JOIN PRODUCTO P ON P.ID_PRODUCTO = I.ID_PRODUCTO
JOIN CATEGORIA CA ON CA.ID_CATEGORIA = P.ID_CATEGORIA;

CREATE OR REPLACE VIEW V_KARDEX AS
SELECT K.ID_KARDEX,
       K.FECHA,
       S.ID_SUCURSAL,
       S.NOMBRE AS SUCURSAL,
       P.ID_PRODUCTO,
       P.CODIGO AS CODIGO_PRODUCTO,
       P.NOMBRE AS PRODUCTO,
       K.TIPO_MOVIMIENTO,
       K.CANTIDAD,
       K.EXISTENCIA_ANTERIOR,
       K.EXISTENCIA_NUEVA,
       K.DOCUMENTO_ORIGEN,
       K.ID_DOCUMENTO,
       K.CREADO_POR
FROM KARDEX K
JOIN SUCURSAL S ON S.ID_SUCURSAL = K.ID_SUCURSAL
JOIN PRODUCTO P ON P.ID_PRODUCTO = K.ID_PRODUCTO;

CREATE OR REPLACE VIEW V_VENTAS_MENSUALES AS
SELECT S.ID_SUCURSAL,
       S.NOMBRE AS SUCURSAL,
       TRUNC(F.FECHA, 'MM') AS MES,
       COUNT(*) AS NUMERO_FACTURAS,
       SUM(F.TOTAL) AS TOTAL_VENDIDO
FROM FACTURA F
JOIN SUCURSAL S ON S.ID_SUCURSAL = F.ID_SUCURSAL
JOIN ESTADO E ON E.ID_ESTADO = F.ID_ESTADO
WHERE E.CODIGO <> 'NC_TOTAL'
GROUP BY S.ID_SUCURSAL, S.NOMBRE, TRUNC(F.FECHA, 'MM');

CREATE OR REPLACE VIEW V_MENU_USUARIO AS
SELECT U.ID_USUARIO,
       U.USERNAME,
       O.ID_OPCION,
       O.ID_OPCION_PADRE,
       O.NOMBRE,
       O.RUTA,
       O.ICONO,
       O.ORDEN,
       RO.PUEDE_CONSULTAR,
       RO.PUEDE_CREAR,
       RO.PUEDE_EDITAR,
       RO.PUEDE_ELIMINAR
FROM USUARIO U
JOIN ROL R ON R.ID_ROL = U.ID_ROL
JOIN ROL_OPCION RO ON RO.ID_ROL = R.ID_ROL
JOIN OPCION_MENU O ON O.ID_OPCION = RO.ID_OPCION
JOIN ESTADO EO ON EO.ID_ESTADO = O.ID_ESTADO
JOIN ESTADO ER ON ER.ID_ESTADO = R.ID_ESTADO
WHERE EO.CODIGO = 'A'
  AND ER.CODIGO = 'A'
  AND RO.PUEDE_CONSULTAR = 'S';

