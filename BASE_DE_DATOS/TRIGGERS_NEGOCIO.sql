CREATE OR REPLACE PROCEDURE PR_MOVIMIENTO_INVENTARIO (
    p_id_sucursal      IN NUMBER,
    p_id_producto      IN NUMBER,
    p_tipo_movimiento  IN VARCHAR2,
    p_cantidad         IN NUMBER,
    p_documento_origen IN VARCHAR2,
    p_id_documento     IN NUMBER
)
IS
    v_anterior INVENTARIO.EXISTENCIA%TYPE;
    v_nueva    INVENTARIO.EXISTENCIA%TYPE;
BEGIN
    BEGIN
        SELECT EXISTENCIA INTO v_anterior
        FROM INVENTARIO
        WHERE ID_SUCURSAL = p_id_sucursal
          AND ID_PRODUCTO = p_id_producto
        FOR UPDATE;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            v_anterior := NULL;
    END;

    IF p_tipo_movimiento IN ('COMPRA', 'NOTA_CREDITO', 'TRASLADO_ENTRADA', 'AJUSTE_ENTRADA') THEN
        v_nueva := NVL(v_anterior, 0) + p_cantidad;
    ELSE
        v_nueva := NVL(v_anterior, 0) - p_cantidad;
    END IF;

    IF v_nueva < 0 THEN
        RAISE_APPLICATION_ERROR(-20020, 'Existencia insuficiente del producto ' || p_id_producto || ' en la sucursal ' || p_id_sucursal);
    END IF;

    IF v_anterior IS NULL THEN
        INSERT INTO INVENTARIO (ID_SUCURSAL, ID_PRODUCTO, EXISTENCIA)
        VALUES (p_id_sucursal, p_id_producto, v_nueva);
    ELSE
        UPDATE INVENTARIO
        SET EXISTENCIA = v_nueva
        WHERE ID_SUCURSAL = p_id_sucursal
          AND ID_PRODUCTO = p_id_producto;
    END IF;

    INSERT INTO KARDEX (ID_SUCURSAL, ID_PRODUCTO, TIPO_MOVIMIENTO, CANTIDAD, EXISTENCIA_ANTERIOR, EXISTENCIA_NUEVA, DOCUMENTO_ORIGEN, ID_DOCUMENTO)
    VALUES (p_id_sucursal, p_id_producto, p_tipo_movimiento, p_cantidad, NVL(v_anterior, 0), v_nueva, p_documento_origen, p_id_documento);
END;
/

CREATE OR REPLACE TRIGGER TRG_DETALLE_FACTURA_NEGOCIO
BEFORE INSERT ON DETALLE_FACTURA
FOR EACH ROW
DECLARE
    v_fecha       FACTURA.FECHA%TYPE;
    v_id_sucursal FACTURA.ID_SUCURSAL%TYPE;
    v_meses       PRODUCTO.MESES_GARANTIA%TYPE;
BEGIN
    SELECT FECHA, ID_SUCURSAL INTO v_fecha, v_id_sucursal
    FROM FACTURA
    WHERE ID_FACTURA = :NEW.ID_FACTURA;

    SELECT MESES_GARANTIA INTO v_meses
    FROM PRODUCTO
    WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO;

    :NEW.FECHA_INICIO_GARANTIA := TRUNC(v_fecha);
    :NEW.FECHA_FIN_GARANTIA := ADD_MONTHS(TRUNC(v_fecha), v_meses);

    PR_MOVIMIENTO_INVENTARIO(v_id_sucursal, :NEW.ID_PRODUCTO, 'VENTA', :NEW.CANTIDAD, 'FACTURA', :NEW.ID_FACTURA);
END;
/

CREATE OR REPLACE TRIGGER TRG_DETALLE_NC_NEGOCIO
BEFORE INSERT ON DETALLE_NOTA_CREDITO
FOR EACH ROW
DECLARE
    v_id_sucursal FACTURA.ID_SUCURSAL%TYPE;
    v_id_producto DETALLE_FACTURA.ID_PRODUCTO%TYPE;
BEGIN
    BEGIN
        SELECT F.ID_SUCURSAL, D.ID_PRODUCTO INTO v_id_sucursal, v_id_producto
        FROM DETALLE_FACTURA D
        JOIN FACTURA F ON F.ID_FACTURA = D.ID_FACTURA
        JOIN NOTA_CREDITO N ON N.ID_FACTURA = F.ID_FACTURA
        WHERE D.ID_DETALLE_FACTURA = :NEW.ID_DETALLE_FACTURA
          AND N.ID_NOTA_CREDITO = :NEW.ID_NOTA_CREDITO;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20028, 'La línea no pertenece a la factura de la nota de crédito');
    END;

    IF :NEW.CANTIDAD > FN_CANTIDAD_PENDIENTE_NC(:NEW.ID_DETALLE_FACTURA) THEN
        RAISE_APPLICATION_ERROR(-20022, 'La cantidad supera lo pendiente de devolver en la línea');
    END IF;

    IF :NEW.MONTO > FN_MONTO_PENDIENTE_NC(:NEW.ID_DETALLE_FACTURA) THEN
        RAISE_APPLICATION_ERROR(-20023, 'El monto supera lo pendiente de acreditar en la línea');
    END IF;

    IF :NEW.REINGRESA_INVENTARIO = 'S' THEN
        PR_MOVIMIENTO_INVENTARIO(v_id_sucursal, v_id_producto, 'NOTA_CREDITO', :NEW.CANTIDAD, 'NOTA_CREDITO', :NEW.ID_NOTA_CREDITO);
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_GARANTIA_NEGOCIO
BEFORE INSERT OR UPDATE ON GARANTIA
FOR EACH ROW
DECLARE
    v_cambiada    ESTADO.ID_ESTADO%TYPE;
    v_id_sucursal EMPLEADO.ID_SUCURSAL%TYPE;
BEGIN
    IF :NEW.ID_GARANTIA IS NULL THEN
        :NEW.ID_GARANTIA := SEQ_GARANTIA.NEXTVAL;
    END IF;

    IF INSERTING AND FN_GARANTIA_VIGENTE(:NEW.ID_DETALLE_FACTURA, :NEW.FECHA_RECLAMO) = 'N' THEN
        RAISE_APPLICATION_ERROR(-20021, 'El reclamo está fuera de la cobertura de garantía');
    END IF;

    IF INSERTING AND FN_CANTIDAD_PENDIENTE_NC(:NEW.ID_DETALLE_FACTURA) = 0 THEN
        RAISE_APPLICATION_ERROR(-20029, 'El producto ya fue devuelto con nota de crédito');
    END IF;

    v_cambiada := FN_ID_ESTADO('GARANTIA', 'CAMBIADA');

    IF :NEW.ID_ESTADO = v_cambiada
       AND :NEW.ID_PRODUCTO_REEMPLAZO IS NOT NULL
       AND (INSERTING OR :OLD.ID_ESTADO <> v_cambiada) THEN
        SELECT ID_SUCURSAL INTO v_id_sucursal
        FROM EMPLEADO
        WHERE ID_EMPLEADO = :NEW.ID_EMPLEADO;

        PR_MOVIMIENTO_INVENTARIO(v_id_sucursal, :NEW.ID_PRODUCTO_REEMPLAZO, 'GARANTIA_CAMBIO', 1, 'GARANTIA', :NEW.ID_GARANTIA);
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_COMPRA_NEGOCIO
AFTER INSERT OR UPDATE OF ID_ESTADO ON COMPRA
FOR EACH ROW
DECLARE
    v_pendiente ESTADO.ID_ESTADO%TYPE;
    v_recibida  ESTADO.ID_ESTADO%TYPE;
BEGIN
    v_pendiente := FN_ID_ESTADO('COMPRA', 'PENDIENTE');
    v_recibida := FN_ID_ESTADO('COMPRA', 'RECIBIDA');

    IF INSERTING THEN
        IF :NEW.ID_ESTADO <> v_pendiente THEN
            RAISE_APPLICATION_ERROR(-20024, 'Una compra se registra en estado PENDIENTE');
        END IF;
    ELSIF :OLD.ID_ESTADO <> :NEW.ID_ESTADO THEN
        IF :OLD.ID_ESTADO <> v_pendiente THEN
            RAISE_APPLICATION_ERROR(-20024, 'Solo una compra PENDIENTE puede cambiar de estado');
        END IF;

        IF :NEW.ID_ESTADO = v_recibida THEN
            FOR d IN (SELECT ID_PRODUCTO, CANTIDAD FROM DETALLE_COMPRA WHERE ID_COMPRA = :NEW.ID_COMPRA) LOOP
                PR_MOVIMIENTO_INVENTARIO(:NEW.ID_SUCURSAL, d.ID_PRODUCTO, 'COMPRA', d.CANTIDAD, 'COMPRA', :NEW.ID_COMPRA);
            END LOOP;
        END IF;
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_DETALLE_TRASLADO_NEGOCIO
BEFORE INSERT ON DETALLE_TRASLADO
FOR EACH ROW
DECLARE
    v_id_origen TRASLADO.ID_SUCURSAL_ORIGEN%TYPE;
    v_id_estado TRASLADO.ID_ESTADO%TYPE;
BEGIN
    SELECT ID_SUCURSAL_ORIGEN, ID_ESTADO INTO v_id_origen, v_id_estado
    FROM TRASLADO
    WHERE ID_TRASLADO = :NEW.ID_TRASLADO;

    IF v_id_estado <> FN_ID_ESTADO('TRASLADO', 'ENVIADO') THEN
        RAISE_APPLICATION_ERROR(-20027, 'Solo se agregan productos a un traslado ENVIADO');
    END IF;

    PR_MOVIMIENTO_INVENTARIO(v_id_origen, :NEW.ID_PRODUCTO, 'TRASLADO_SALIDA', :NEW.CANTIDAD, 'TRASLADO', :NEW.ID_TRASLADO);
END;
/

CREATE OR REPLACE TRIGGER TRG_TRASLADO_NEGOCIO
AFTER INSERT OR UPDATE OF ID_ESTADO ON TRASLADO
FOR EACH ROW
DECLARE
    v_enviado   ESTADO.ID_ESTADO%TYPE;
    v_recibido  ESTADO.ID_ESTADO%TYPE;
    v_cancelado ESTADO.ID_ESTADO%TYPE;
BEGIN
    v_enviado := FN_ID_ESTADO('TRASLADO', 'ENVIADO');
    v_recibido := FN_ID_ESTADO('TRASLADO', 'RECIBIDO');
    v_cancelado := FN_ID_ESTADO('TRASLADO', 'CANCELADO');

    IF INSERTING THEN
        IF :NEW.ID_ESTADO <> v_enviado THEN
            RAISE_APPLICATION_ERROR(-20025, 'Un traslado se registra en estado ENVIADO');
        END IF;
    ELSIF :OLD.ID_ESTADO <> :NEW.ID_ESTADO THEN
        IF :OLD.ID_ESTADO <> v_enviado THEN
            RAISE_APPLICATION_ERROR(-20025, 'Solo un traslado ENVIADO puede cambiar de estado');
        END IF;

        FOR d IN (SELECT ID_PRODUCTO, CANTIDAD FROM DETALLE_TRASLADO WHERE ID_TRASLADO = :NEW.ID_TRASLADO) LOOP
            IF :NEW.ID_ESTADO = v_recibido THEN
                PR_MOVIMIENTO_INVENTARIO(:NEW.ID_SUCURSAL_DESTINO, d.ID_PRODUCTO, 'TRASLADO_ENTRADA', d.CANTIDAD, 'TRASLADO', :NEW.ID_TRASLADO);
            ELSIF :NEW.ID_ESTADO = v_cancelado THEN
                PR_MOVIMIENTO_INVENTARIO(:NEW.ID_SUCURSAL_ORIGEN, d.ID_PRODUCTO, 'TRASLADO_ENTRADA', d.CANTIDAD, 'TRASLADO', :NEW.ID_TRASLADO);
            END IF;
        END LOOP;
    END IF;
END;
/

CREATE OR REPLACE TRIGGER TRG_AJUSTE_INVENTARIO_NEGOCIO
BEFORE INSERT OR UPDATE OF ID_ESTADO ON AJUSTE_INVENTARIO
FOR EACH ROW
DECLARE
    v_aplicado ESTADO.ID_ESTADO%TYPE;
    v_anulado  ESTADO.ID_ESTADO%TYPE;
BEGIN
    v_aplicado := FN_ID_ESTADO('AJUSTE_INVENTARIO', 'APLICADO');
    v_anulado := FN_ID_ESTADO('AJUSTE_INVENTARIO', 'ANULADO');

    IF :NEW.ID_AJUSTE IS NULL THEN
        :NEW.ID_AJUSTE := SEQ_AJUSTE_INVENTARIO.NEXTVAL;
    END IF;

    IF INSERTING THEN
        IF :NEW.ID_ESTADO <> v_aplicado THEN
            RAISE_APPLICATION_ERROR(-20026, 'Un ajuste se registra en estado APLICADO');
        END IF;

        PR_MOVIMIENTO_INVENTARIO(:NEW.ID_SUCURSAL, :NEW.ID_PRODUCTO, 'AJUSTE_' || :NEW.TIPO_AJUSTE, :NEW.CANTIDAD, 'AJUSTE', :NEW.ID_AJUSTE);
    ELSIF :OLD.ID_ESTADO <> :NEW.ID_ESTADO THEN
        IF :OLD.ID_ESTADO <> v_aplicado OR :NEW.ID_ESTADO <> v_anulado THEN
            RAISE_APPLICATION_ERROR(-20026, 'Solo un ajuste APLICADO puede anularse');
        END IF;

        IF :OLD.TIPO_AJUSTE = 'ENTRADA' THEN
            PR_MOVIMIENTO_INVENTARIO(:OLD.ID_SUCURSAL, :OLD.ID_PRODUCTO, 'AJUSTE_SALIDA', :OLD.CANTIDAD, 'AJUSTE', :OLD.ID_AJUSTE);
        ELSE
            PR_MOVIMIENTO_INVENTARIO(:OLD.ID_SUCURSAL, :OLD.ID_PRODUCTO, 'AJUSTE_ENTRADA', :OLD.CANTIDAD, 'AJUSTE', :OLD.ID_AJUSTE);
        END IF;
    END IF;
END;
/

SELECT object_name, object_type, status
FROM user_objects
WHERE object_name = 'PR_MOVIMIENTO_INVENTARIO'
   OR object_name LIKE '%NEGOCIO'
ORDER BY object_type, object_name;
